import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdtemp, mkdir, readFile, realpath, rm, symlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import test, { afterEach } from 'node:test'

import { createReachabilityReport } from './summarize.mjs'

const ROOT_MODULE = 'github.com/ForceMind/MyAPI'
const RELAYKIT_MODULE = `${ROOT_MODULE}/relaykit`
const roots = []
afterEach(async () => {
  for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true })
})

async function repository() {
  const root = await realpath(await mkdtemp(path.join(tmpdir(), 'myapi-reachability-contract-')))
  roots.push(root)
  await mkdir(path.join(root, 'relaykit'))
  const sources = {
    'go.mod': `module ${ROOT_MODULE}\n\ngo 1.25\n\nrequire ${RELAYKIT_MODULE} v0.0.0\nreplace ${RELAYKIT_MODULE} => ./relaykit\n`,
    'relaykit/go.mod': `module ${RELAYKIT_MODULE}\n\ngo 1.25\n`,
    'main.go': `package main\nimport _ "${RELAYKIT_MODULE}"\n\nfunc main() {}\nfunc dormant() {}\nfunc exercisedByTest() {}\nfunc ExportedAPI() {}\nfunc ΩpenAPI() {}\nfunc init() {}\ntype record struct{}\nfunc (r *record) BeforeCreate() error { return nil }\nfunc (r record) MarshalJSON() ([]byte, error) { return []byte("null"), nil }\nfunc (δ record) scan() {}\n`,
    'anonymous.go': 'package main\nvar closure = func() {}\n',
    'generated.go': '// Code generated by the contract fixture. DO NOT EDIT.\npackage main\nfunc generatedHelper() {}\n',
    'helpers_test.go': 'package main\nfunc privateTestHelper() {}\n',
    'quota_helpers.go': 'package main\nfunc quotaHelper() {}\n',
    'relaykit/api.go': 'package relaykit\nfunc PublicAPI() {}\nfunc internalHelper() {}\n',
  }
  for (const [name, content] of Object.entries(sources)) await writeFile(path.join(root, name), content)
  return {
    root, sources,
    fn(file, name, token = name, generated = false) {
      const lines = sources[file].split('\n')
      const line = lines.findIndex((value) => value.includes(token))
      assert.ok(line >= 0, `fixture source token ${token}`)
      const index = lines[line].indexOf(token)
      return { Name: name, Position: { File: path.join(root, file), Line: line + 1, Col: Buffer.byteLength(lines[line].slice(0, index), 'utf8') + 1 }, Generated: generated }
    },
  }
}

function pkg(functions, nested = false) {
  return { Name: nested ? 'relaykit' : 'main', Path: nested ? RELAYKIT_MODULE : ROOT_MODULE, Funcs: functions }
}

function inputs(repo, options = {}) {
  return {
    repositoryRoot: repo.root,
    sourceSha: 'a'.repeat(40),
    tool: { module: 'golang.org/x/tools/cmd/deadcode', version: 'v0.38.0' },
    target: { goos: 'linux', goarch: 'amd64' },
    run: { id: '123456789', attempt: '1' },
    scans: {
      root_production: { json: JSON.stringify(options.production ?? []), exit_code: 0 },
      root_with_tests: { json: JSON.stringify(options.tests ?? []), exit_code: 0 },
      relaykit_with_tests: { json: JSON.stringify(options.relaykit ?? []), exit_code: 0 },
    },
  }
}

function find(report, file, name) {
  const record = report.records.find((item) => item.file === file && item.name === name)
  assert.ok(record, `expected record ${file}:${name}`)
  return record
}

test('a private function dead in both root scans is only a source-bound manual review candidate, while test reachability protects its neighbour', async () => {
  const repo = await repository()
  const dormant = repo.fn('main.go', 'dormant')
  const exercised = repo.fn('main.go', 'exercisedByTest')
  const report = await createReachabilityReport(inputs(repo, { production: [pkg([dormant, exercised])], tests: [pkg([dormant])] }))
  assert.equal(report.schema_version, 1)
  assert.equal(report.source_sha, 'a'.repeat(40))
  assert.deepEqual(report.tool, { module: 'golang.org/x/tools/cmd/deadcode', version: 'v0.38.0' })
  assert.deepEqual(report.target, { goos: 'linux', goarch: 'amd64' })
  assert.deepEqual(report.run, { id: '123456789', attempt: '1' })
  assert.equal(report.analysis_only, true)
  assert.equal(report.deletion_authorized, false)
  assert.ok(report.records.every((record) => record.deletion_authorized === false))
  const candidate = find(report, 'main.go', 'dormant')
  assert.equal(candidate.module, 'root')
  assert.equal(candidate.package, ROOT_MODULE)
  assert.equal(candidate.unreachable_in_production, true)
  assert.equal(candidate.unreachable_with_tests, true)
  assert.equal(candidate.test_reachable_only, false)
  assert.equal(candidate.manual_review_candidate, true)
  assert.deepEqual(candidate.protections, [])
  assert.equal(candidate.symbol_verified, true)
  assert.equal(candidate.line, dormant.Position.Line)
  assert.equal(candidate.column, dormant.Position.Col)
  assert.equal(candidate.file_sha256, createHash('sha256').update(await readFile(path.join(repo.root, 'main.go'))).digest('hex'))
  assert.deepEqual(candidate.source_range, { start_line: dormant.Position.Line, end_line: dormant.Position.Line })
  const kept = find(report, 'main.go', 'exercisedByTest')
  assert.equal(kept.unreachable_in_production, true)
  assert.equal(kept.unreachable_with_tests, false)
  assert.equal(kept.test_reachable_only, true)
  assert.ok(kept.protections.includes('test-reachable-only'))
  assert.equal(kept.manual_review_candidate, false)
  assert.ok(Array.isArray(report.unsupported_checks) && report.unsupported_checks.length > 0)
})

test('exported Unicode Lu APIs, framework methods, init, generated code and test sources all remain protected', async () => {
  const repo = await repository()
  const ordinary = [
    repo.fn('main.go', 'ExportedAPI'), repo.fn('main.go', 'ΩpenAPI'), repo.fn('main.go', 'init#1', 'init'),
    repo.fn('main.go', '(*record).BeforeCreate', 'BeforeCreate'), repo.fn('main.go', 'record.MarshalJSON', 'MarshalJSON'),
    repo.fn('main.go', 'record.scan', 'scan'), repo.fn('generated.go', 'generatedHelper', 'generatedHelper', true),
  ]
  const testHelper = repo.fn('helpers_test.go', 'privateTestHelper')
  const report = await createReachabilityReport(inputs(repo, { production: [pkg(ordinary)], tests: [pkg([...ordinary, testHelper])] }))
  for (const name of ['ExportedAPI', 'ΩpenAPI']) {
    const api = find(report, 'main.go', name)
    assert.equal(api.exported, true)
    assert.ok(api.protections.includes('exported-api'))
  }
  for (const name of ['(*record).BeforeCreate', 'record.MarshalJSON', 'record.scan']) {
    const method = find(report, 'main.go', name)
    assert.equal(method.method, true)
    assert.ok(method.protections.includes('method-or-hook'))
  }
  assert.ok(find(report, 'main.go', 'init#1').protections.includes('init'))
  assert.ok(find(report, 'generated.go', 'generatedHelper').protections.includes('generated'))
  const testSource = find(report, 'helpers_test.go', 'privateTestHelper')
  assert.ok(testSource.protections.includes('test-source'))
  assert.equal(testSource.unreachable_in_production, null)
  assert.equal(testSource.test_reachable_only, null)
  assert.ok(report.records.every((record) => record.manual_review_candidate === false))
  // The unexported method's Unicode receiver makes its byte column differ
  // from a JavaScript string offset; the validated source location is retained.
  assert.equal(find(report, 'main.go', 'record.scan').column, repo.fn('main.go', 'record.scan', 'scan').Position.Col)
})

test('an anonymous func literal has an unknown-symbol protection and cannot become a guessed private-function candidate', async () => {
  const repo = await repository()
  const anonymous = repo.fn('anonymous.go', 'closure$1', 'func')
  const report = await createReachabilityReport(inputs(repo, { production: [pkg([anonymous])], tests: [pkg([anonymous])] }))
  const record = find(report, 'anonymous.go', 'closure$1')
  assert.ok(record.protections.includes('unknown-symbol'))
  assert.equal(record.manual_review_candidate, false)
})

test('nested relaykit records from the root CLI never become root deletion candidates or root test-only claims', async () => {
  const repo = await repository()
  const api = repo.fn('relaykit/api.go', 'PublicAPI')
  const helper = repo.fn('relaykit/api.go', 'internalHelper')
  const report = await createReachabilityReport(inputs(repo, { production: [pkg([api, helper], true)], tests: [pkg([api, helper], true)], relaykit: [pkg([api, helper], true)] }))
  assert.equal(report.records.length, 2)
  for (const record of report.records) {
    assert.equal(record.module, 'relaykit')
    assert.equal(record.package, RELAYKIT_MODULE)
    assert.ok(record.protections.includes('relaykit-public-boundary'))
    assert.equal(record.unreachable_in_production, null)
    assert.equal(record.test_reachable_only, null)
    assert.equal(record.unreachable_with_tests, true)
    assert.equal(record.manual_review_candidate, false)
    assert.equal(record.scan_presence.root_production, true)
    assert.equal(record.scan_presence.root_with_tests, true)
    assert.equal(record.scan_presence.relaykit_with_tests, true)
  }
})

test('a billing-adjacent name is labelled heuristic-only rather than confirmed billing involvement or deletion authority', async () => {
  const repo = await repository()
  const helper = repo.fn('quota_helpers.go', 'quotaHelper')
  const report = await createReachabilityReport(inputs(repo, { production: [pkg([helper])], tests: [pkg([helper])] }))
  const record = find(report, 'quota_helpers.go', 'quotaHelper')
  assert.equal(record.billing_adjacent, true)
  assert.equal(record.billing_basis, 'heuristic-only')
  assert.equal(record.manual_review_candidate, true)
  assert.equal(report.deletion_authorized, false)
})

for (const json of ['null', '[]']) {
  test(`successful ${json} scans are valid zero-record evidence, not missing analysis`, async () => {
    const repo = await repository()
    const input = inputs(repo)
    for (const scan of Object.values(input.scans)) scan.json = json
    const report = await createReachabilityReport(input)
    assert.deepEqual(report.records, [])
    assert.equal(report.analysis_only, true)
    assert.equal(report.deletion_authorized, false)
  })
}

for (const json of ['', '  ', '{broken', '{}', '[{"Name":"main","Path":"github.com/ForceMind/MyAPI"}]']) {
  test(`empty, malformed or partial scan input is rejected instead of converted to zero: ${JSON.stringify(json)}`, async () => {
    const repo = await repository()
    const input = inputs(repo)
    input.scans.root_production.json = json
    await assert.rejects(createReachabilityReport(input))
  })
}

test('a failed tool or absent target scan invalidates the report even when all other scans have no records', async () => {
  const repo = await repository()
  const failed = inputs(repo)
  failed.scans.root_with_tests = { exit_code: 1, json: 'null' }
  await assert.rejects(createReachabilityReport(failed))
  const partial = inputs(repo)
  delete partial.scans.relaykit_with_tests
  await assert.rejects(createReachabilityReport(partial))
})

test('outside files, symlinked sources and incorrect line/byte-column locations are rejected without guessing a source range', async () => {
  const repo = await repository()
  const outside = await mkdtemp(path.join(tmpdir(), 'myapi-reachability-outside-'))
  roots.push(outside)
  await writeFile(path.join(outside, 'outside.go'), 'package main\nfunc dormant() {}\n')
  await symlink(path.join(outside, 'outside.go'), path.join(repo.root, 'linked.go'))
  const valid = repo.fn('main.go', 'dormant')
  for (const position of [
    { File: path.join(outside, 'outside.go'), Line: 2, Col: 6 },
    { File: path.join('..', path.basename(outside), 'outside.go'), Line: 2, Col: 6 },
    { File: path.join(repo.root, 'linked.go'), Line: 2, Col: 6 },
    { ...valid.Position, Line: 0 }, { ...valid.Position, Line: 999 }, { ...valid.Position, Col: 999 },
    { ...valid.Position, Line: repo.fn('main.go', 'exercisedByTest').Position.Line },
  ]) {
    const bad = { ...valid, Position: position }
    await assert.rejects(createReachabilityReport(inputs(repo, { production: [pkg([bad])] })))
  }
  const generatedOutside = { ...valid, Generated: true, Position: { File: path.join(outside, 'outside.go'), Line: 2, Col: 6 } }
  await assert.rejects(createReachabilityReport(inputs(repo, { production: [pkg([generatedOutside])] })))
})

test('source text in a comment or string cannot impersonate a real named function declaration', async () => {
  const repo = await repository()
  const content = 'package main\n// func ghostComment() {}\nvar text = "func ghostString() {}"\nfunc realFunction() {}\n'
  repo.sources['deceptive.go'] = content
  await writeFile(path.join(repo.root, 'deceptive.go'), content)
  for (const name of ['ghostComment', 'ghostString']) {
    const fake = repo.fn('deceptive.go', name)
    await assert.rejects(createReachabilityReport(inputs(repo, { production: [pkg([fake])] })))
  }
})

test('duplicate and conflicting scan records are rejected rather than merged into a misleading candidate count', async () => {
  const repo = await repository()
  const functionRecord = repo.fn('main.go', 'dormant')
  await assert.rejects(createReachabilityReport(inputs(repo, { production: [pkg([functionRecord, functionRecord])] })))
  await assert.rejects(createReachabilityReport(inputs(repo, { production: [pkg([functionRecord, { ...functionRecord, Name: 'unknown$1' }])] })))
  const input = inputs(repo, { production: [pkg([functionRecord])], tests: [pkg([{ ...functionRecord, Generated: true }])] })
  await assert.rejects(createReachabilityReport(input))
})

test('source identity, fixed tool and run-attempt metadata cannot silently float to another analysis', async () => {
  const repo = await repository()
  for (const changes of [
    { sourceSha: 'unknown' }, { tool: { module: 'golang.org/x/tools/cmd/deadcode', version: 'latest' } },
    { run: { id: '123456789', attempt: '0' } },
  ]) await assert.rejects(createReachabilityReport({ ...inputs(repo), ...changes }))
})
