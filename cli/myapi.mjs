const [command = 'help', ...args] = process.argv.slice(2)

try {
  if (command === 'init') {
    validateArguments(args, { positional: 1 })
    initProject(args)
  } else if (command === 'configure') {
    validateArguments(args, {
      values: [
        '--project-dir',
        '--public-url',
        '--data-dir',
        '--logs-dir',
      ],
      flags: ['--force'],
    })
    configureProject(args)
  } else if (command === 'migrate') {
    validateArguments(args, { values: ['--project-dir'] })
    migrateDeploymentEnv(args)
  } else if (command === 'doctor') {
    validateArguments(args, { values: ['--project-dir'] })
    doctor(args)
  } else if (command === 'upgrade') {
    validateArguments(args, {
      values: ['--project-dir', '--version'],
      flags: ['--verify-signature', '--pin-digest', '--dry-run', '--json'],
    })
    if (args.includes('--json') && !args.includes('--dry-run')) {
      throw new Error('--json is only supported with --dry-run')
    }
    if (args.includes('--dry-run')) printUpgradeDryRun(buildUpgradePlan(args), args)
    else upgradeDeployment(args)
  } else if (command === 'adopt') {
    validateArguments(args, {
      values: ['--project-dir', '--data-dir', '--logs-dir'],
    })
    adoptDataPaths(args)
  } else if (command === 'lan') {
    const [lanSubcommand = 'help', ...lanArgs] = args
    if (lanSubcommand === 'help' || lanSubcommand === '--help' || lanSubcommand === '-h') {
      printHelp()
    } else {
      if (!['init', 'start', 'status', 'stop'].includes(lanSubcommand)) {
        throw new Error('LAN command must be init, start, status, or stop')
      }
      validateArguments(lanArgs, {
        positional: lanSubcommand === 'init' ? 1 : 0,
        values: ['--project-dir', '--bind-address', '--port'],
        flags: ['--allow-lan'],
      })
      lanCommand(lanSubcommand, lanArgs)
    }
  } else if (['build', 'up', 'down', 'status', 'logs'].includes(command)) {
    validateArguments(args, {
      values: ['--project-dir'],
      flags: command === 'logs' ? ['--follow'] : [],
    })
    deploymentCommand(command, args)
  } else if (command === 'version' || command === '--version' || command === '-v') {
    validateArguments(args, { flags: ['--json'] })
    printVersion(args)
  } else if (command === 'help' || command === '--help' || command === '-h') {
    printHelp()
  } else {
    fail(`unknown command "${command}"`)
    printHelp()
  }
} catch (error) {
  fail(error instanceof Error ? error.message : String(error))
}
